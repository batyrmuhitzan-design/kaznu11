/**
 * 真实文件导出 / 保存 / 分享（iOS 原生）：
 *  - @capacitor/filesystem   → 真实写入本地 Documents / Cache（含父目录自动创建）
 *  - @capacitor/action-sheet → 下载完成后询问“在‘文件’中查看 / 发送分享”
 *  - @capacitor/share        → 原生 iOS Share Sheet（AirDrop / 存到“文件” / Telegram / 微信 / 打印）
 *  - jspdf                   → 动态生成标准 .pdf（资料离线副本 / 学业成绩单）
 *
 * 纯 Web 预览：原生接口不可用时，退回真实浏览器下载（Blob + <a download>）。
 */
