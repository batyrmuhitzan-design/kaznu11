export const isNative = () => Capacitor.isNativePlatform();

/** 用户在“文件”App 中可见的下载目录（相对 Documents） */
export const APP_DOCS_FOLDER = "KazNU Helper/Downloads";

/** 供系统分享用的临时导出目录（相对 Cache，系统可自动清理） */
export const APP_TMP_FOLDER = "kaznu-helper/exports";

/** 把非 ASCII 排版符号换成可读 ASCII，保证 PDF / 文件名不出现乱码方块。 */
function pdfSafe(text: string): string {
  const aliases: Array<[RegExp, string]> = [
    [/[–—]/g, "-"],
    [/[·•]/g, " - "],
    [/[’‘]/g, "'"],
    [/[“”]/g, '"'],
    [/…/g, "..."],
    [/₸/g, "KZT"],
    [/≥/g, ">="],
    [/≤/g, "<="],
  ];
  let out = text;
  for (const [re, to] of aliases) out = out.replace(re, to);
  return out
    .replace(/[^\x20-\x7E]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/** 文件名清洗：去掉 / : * ? " < > | 与非法尾点，返回可落盘的 basename（不含扩展名）。 */
export function sanitizeBaseName(name: string): string {
  return pdfSafe(name)
    .replace(/[\\/:*?"<>|]/g, "-")
    .replace(/[.\s]+$/g, "")
    .slice(0, 90);
}

export function toPdfFileName(base: string, suffix = ""): string {
  const clean = sanitizeBaseName(base) || "document";
  return suffix ? `${clean}-${suffix}.pdf` : `${clean}.pdf`;
}

/* ===================== jsPDF 生成器 ===================== */

const PAGE_W = 595; // A4 (pt)
const PAGE_H = 842;
const MARGIN = 46;

function drawFooter(doc: jsPDF, generatedAt: Date) {
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(120, 120, 128);
    const footer = `KazNU Helper - Al-Farabi Kazakh National University   |   ${generatedAt.toLocaleString("en-GB", { hour12: false })}`;
    doc.text(pdfSafe(footer), MARGIN, PAGE_H - 28);
    doc.text(`${i} / ${pages}`, PAGE_W - MARGIN, PAGE_H - 28, { align: "right" });
  }
}

/** 资料下载时生成的“离线副本”PDF（真实二进制 PDF，写入 Documents 供查看/分享）。 */
export function createMaterialPdf(meta: {
  course: string;
  code: string;
  prof: string;
  title: string;
  format: string;
  size: string;
  date: string;
}): string {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const now = new Date();

  // 顶部校徽色带
  doc.setFillColor(0, 51, 160);
  doc.rect(0, 0, PAGE_W, 128, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(17);
  doc.text("AL-FARABI KAZAKH NATIONAL UNIVERSITY", MARGIN, 52);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text("KazNU Helper - Offline Course Material", MARGIN, 76);
  doc.text(pdfSafe(meta.course), MARGIN, 100);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.text(pdfSafe(`${meta.code}  |  ${meta.prof}`), PAGE_W - MARGIN, 100, { align: "right" });

  // 标题区
  doc.setTextColor(28, 28, 30);
  doc.setFontSize(23);
  doc.setFont("helvetica", "bold");
  const titleLines = doc.splitTextToSize(pdfSafe(meta.title), PAGE_W - MARGIN * 2) as string[];
  let y = 182;
  doc.text(titleLines, MARGIN, y);
  y += titleLines.length * 28 + 8;
  doc.setDrawColor(220, 220, 224);
  doc.setLineWidth(1);
  doc.line(MARGIN, y, PAGE_W - MARGIN, y);

  // 元信息
  y += 34;
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(70, 70, 74);
  const rows: Array<[string, string]> = [
    ["File format", meta.format],
    ["Displayed size", meta.size],
    ["Published date", meta.date],
    ["Generated by", "KazNU Helper (iOS)"],
  ];
  for (const [k, v] of rows) {
    doc.setFont("helvetica", "bold");
    doc.setTextColor(30, 30, 34);
    doc.text(k, MARGIN, y);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(90, 90, 96);
    doc.text(pdfSafe(v), 190, y);
    y += 24;
  }

  y += 26;
  doc.setFontSize(10);
  doc.setTextColor(120, 120, 128);
  const note = doc.splitTextToSize(
    pdfSafe(
      "This offline copy was generated locally by the KazNU Helper app and saved to your device Documents folder. It is intended for personal study use.",
    ),
    PAGE_W - MARGIN * 2,
  ) as string[];
  doc.text(note, MARGIN, y);

  doc.setFont("helvetica", "bold");
  doc.setTextColor(0, 51, 160);
  doc.setFontSize(12);
  doc.text("KazNU Helper", MARGIN, PAGE_H - 92);
  drawFooter(doc, now);
  return doc.output("datauristring").split(",")[1] ?? "";
}

